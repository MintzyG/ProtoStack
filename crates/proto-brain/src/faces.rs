use crate::framebuffer::{Bitmap1Bit, Framebuffer, Rgb};

/// Built-in animated starter visor expressions shipped in v0.1.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[repr(u8)]
pub enum Expression {
    /// Classic slanted Protogen eyes with periodic blinking and calm closed maw.
    #[default]
    Neutral = 0,
    /// Curved happy eyes with blinking and animated open/closed cheerful maw.
    Happy = 1,
    /// Wide round circle eyes with surprised open maw and subtle bounce.
    Surprised = 2,
}

impl Expression {
    /// Total number of built-in starter expressions.
    pub const COUNT: u8 = 3;

    /// Converts a wire expression ID into an `Expression`, falling back to `Neutral`.
    pub const fn from_u8(value: u8) -> Self {
        match value {
            1 => Self::Happy,
            2 => Self::Surprised,
            _ => Self::Neutral,
        }
    }

    /// Converts the expression into its wire ID.
    pub const fn as_u8(self) -> u8 {
        self as u8
    }
}

/// Computes eye openness percentage (`0..=100`) for a 60-frame (~3 s at 20 FPS) blink cycle.
///
/// Frames 0..53: fully open (100%).
/// Frames 54..59: smooth close and reopen (`60 -> 25 -> 0 -> 25 -> 60 -> 100`).
pub const fn blink_open_pct(frame: u32) -> u8 {
    match frame % 60 {
        54 | 58 => 60,
        55 | 57 => 25,
        56 => 0,
        _ => 100,
    }
}

/// Renders `expression` at animation `frame` into `fb` using `color` (already brightness-scaled).
pub fn render_expression(fb: &mut Framebuffer, expression: Expression, frame: u32, color: Rgb) {
    fb.clear();
    if color == Rgb::BLACK {
        return;
    }

    // Subtle 1px idle vertical bob every ~16 frames.
    let bob_y: i32 = match (frame / 8) % 4 {
        1 => 1,
        _ => 0,
    };
    let open_pct = blink_open_pct(frame);

    match expression {
        Expression::Neutral => {
            fb.draw_bitmap_1bit_blink(2, bob_y, SLANT_EYE_R, color, open_pct);
            fb.draw_bitmap_1bit_blink(102, bob_y, SLANT_EYE_L, color, open_pct);
            draw_nose(fb, color);
            draw_maw_closed(fb, color);
        }
        Expression::Happy => {
            fb.draw_bitmap_1bit_blink(0, bob_y, HAPPY_EYE_R, color, open_pct);
            fb.draw_bitmap_1bit_blink(96, bob_y, HAPPY_EYE_L, color, open_pct);
            draw_nose(fb, color);
            // Alternate between happy closed smile and open joyful maw every 10 frames.
            if (frame / 10).is_multiple_of(2) {
                draw_maw_closed(fb, color);
            } else {
                draw_maw_open(fb, color);
            }
        }
        Expression::Surprised => {
            let eye_y = 2 + bob_y;
            fb.draw_bitmap_1bit_blink(10, eye_y, CIRCLE_EYE, color, open_pct);
            fb.draw_bitmap_1bit_blink(93, eye_y, CIRCLE_EYE, color, open_pct);
            draw_nose(fb, color);
            draw_maw_open(fb, color);
        }
    }
}

fn draw_nose(fb: &mut Framebuffer, color: Rgb) {
    fb.draw_bitmap_1bit(56, 4, NOSE_R, color);
    fb.draw_bitmap_1bit(64, 4, NOSE_L, color);
}

fn draw_maw_closed(fb: &mut Framebuffer, color: Rgb) {
    fb.draw_bitmap_1bit(0, 10, MAW_CLOSED_R, color);
    fb.draw_bitmap_1bit(64, 10, MAW_CLOSED_L, color);
}

fn draw_maw_open(fb: &mut Framebuffer, color: Rgb) {
    fb.draw_bitmap_1bit(0, 10, MAW_OPEN_R, color);
    fb.draw_bitmap_1bit(64, 10, MAW_OPEN_L, color);
}

